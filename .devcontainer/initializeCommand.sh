#!/bin/bash

if [ ! -f .env.local ]; then
    echo "Warning, .env.local file not found. Creating a new one. If you need to set local environment variables, please edit the .env.local file."
    touch .env.local
else
  echo ".env.local file already exists."
fi

# Write a unique identifier to .env.local, mark as do not change this value UNIQUE_WEBHOOK_SUBDOMAIN
if ! grep -q '^UNIQUE_WEBHOOK_SUBDOMAIN=' .env.local; then
    UNIQUE_ID=$(head /dev/urandom | tr -dc A-Za-z0-9 | head -c 13 ; echo '')
    echo "" >> .env.local
    echo "UNIQUE_WEBHOOK_SUBDOMAIN=$UNIQUE_ID" >> .env.local
    echo "Added UNIQUE_WEBHOOK_SUBDOMAIN to .env.local"
else
    echo "UNIQUE_WEBHOOK_SUBDOMAIN already set in .env.local"
fi

# Create a data directory if it doesn't exist
mkdir -p ./data

# --- Worktree-aware devcontainer git mount ---------------------------------
# A git worktree's .git is a FILE pointing (absolute path) into the main
# checkout's gitdir, which the devcontainer would not otherwise mount. Without
# that mount, every git command inside the container fails because the absolute
# `gitdir:` pointer resolves to a path that does not exist in the container.
# Generate a git-ignored compose override that identity-path bind-mounts the
# main gitdir (same absolute path on host and container) so the pointer resolves
# unchanged. Plain clones get a harmless no-op override from the committed
# template.
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
WORKTREE_OVERRIDE="$SCRIPT_DIR/docker-compose.worktree.yml"
WORKTREE_TEMPLATE="$SCRIPT_DIR/docker-compose.worktree.yml.in"

if [ -f .git ]; then
    GITDIR="$(sed 's/^gitdir: //' .git)"
    if MAIN_GITDIR="$(cd "$(dirname "$GITDIR")/.." 2>/dev/null && pwd)" && [ -n "$MAIN_GITDIR" ]; then
        cat > "$WORKTREE_OVERRIDE" <<EOF
# Generated by .devcontainer/initializeCommand.sh — do not edit or commit.
# Identity-path mount of the main repo gitdir so git works in this worktree.
services:
  warp:
    volumes:
      - ${MAIN_GITDIR}:${MAIN_GITDIR}:cached
EOF
        echo "Worktree detected; mounting main gitdir $MAIN_GITDIR into the devcontainer"
    else
        echo "Warning: could not resolve main gitdir from .git; writing no-op override"
        cp "$WORKTREE_TEMPLATE" "$WORKTREE_OVERRIDE"
    fi
else
    cp "$WORKTREE_TEMPLATE" "$WORKTREE_OVERRIDE"
    echo "Plain clone; wrote no-op devcontainer git override"
fi