#!/usr/bin/env bash
# Runs on the host before the devcontainer is created. Selects a collision-free
# block of host ports for human-facing Warp endpoints, writes the values to
# ports.env, and generates the Compose override consumed by devcontainer.json.
#
# Containers keep their stable internal ports and communicate through Compose
# DNS. Only endpoints used by a host browser or developer tool are published.
set -euo pipefail

if [ ! -f .env.local ]; then
    echo "Warning, .env.local file not found. Creating a new one. If you need to set local environment variables, please edit the .env.local file."
    touch .env.local
else
    echo ".env.local file already exists."
fi

if ! grep -q '^UNIQUE_WEBHOOK_SUBDOMAIN=' .env.local; then
    UNIQUE_ID=$(head /dev/urandom | tr -dc A-Za-z0-9 | head -c 13 ; echo '')
    echo "" >> .env.local
    echo "UNIQUE_WEBHOOK_SUBDOMAIN=$UNIQUE_ID" >> .env.local
    echo "Added UNIQUE_WEBHOOK_SUBDOMAIN to .env.local"
else
    echo "UNIQUE_WEBHOOK_SUBDOMAIN already set in .env.local"
fi

mkdir -p ./data

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PORTS_ENV="$SCRIPT_DIR/ports.env"
WORKTREE_OVERRIDE="$SCRIPT_DIR/docker-compose.worktree.yml"

# Preferred blocks keep the first checkout on Warp's familiar ports and give
# additional worktrees stable alternative slots. Values are ordered as:
# gateway, developer API, admin API, Latinum, chat, Jaeger.
PREFERRED_BLOCKS=(
    "5000 5002 5003 5004 8888 16686"
    "15000 15002 15003 15004 18888 26686"
    "25000 25002 25003 25004 28888 36686"
    "35000 35002 35003 35004 38888 46686"
    "45000 45002 45003 45004 48888 56686"
)

port_is_free() {
    local port="$1"
    ! ss -tln "sport = :$port" 2>/dev/null | grep -q LISTEN
}

block_is_free() {
    local port
    for port in "$@"; do
        if ! port_is_free "$port"; then
            return 1
        fi
    done
}

kernel_port() {
    python3 -c 'import socket; s = socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()'
}

SELECTED_BLOCK=""
for candidate in "${PREFERRED_BLOCKS[@]}"; do
    read -r -a candidate_ports <<< "$candidate"
    if block_is_free "${candidate_ports[@]}"; then
        SELECTED_BLOCK="$candidate"
        break
    fi
done

if [ -n "$SELECTED_BLOCK" ]; then
    read -r \
        WARP_GATEWAY_HOST_PORT \
        WARP_DEVELOPER_HOST_PORT \
        WARP_ADMIN_HOST_PORT \
        WARP_LATINUM_HOST_PORT \
        WARP_CHAT_HOST_PORT \
        WARP_JAEGER_HOST_PORT <<< "$SELECTED_BLOCK"
else
    declare -A USED_PORTS=()
    pick_unique_kernel_port() {
        local port
        while true; do
            port="$(kernel_port)"
            if [ -z "${USED_PORTS[$port]+x}" ]; then
                USED_PORTS[$port]=1
                echo "$port"
                return
            fi
        done
    }

    WARP_GATEWAY_HOST_PORT="$(pick_unique_kernel_port)"
    WARP_DEVELOPER_HOST_PORT="$(pick_unique_kernel_port)"
    WARP_ADMIN_HOST_PORT="$(pick_unique_kernel_port)"
    WARP_LATINUM_HOST_PORT="$(pick_unique_kernel_port)"
    WARP_CHAT_HOST_PORT="$(pick_unique_kernel_port)"
    WARP_JAEGER_HOST_PORT="$(pick_unique_kernel_port)"
fi

cat > "$PORTS_ENV" <<EOF
WARP_GATEWAY_HOST_PORT=$WARP_GATEWAY_HOST_PORT
WARP_DEVELOPER_HOST_PORT=$WARP_DEVELOPER_HOST_PORT
WARP_ADMIN_HOST_PORT=$WARP_ADMIN_HOST_PORT
WARP_LATINUM_HOST_PORT=$WARP_LATINUM_HOST_PORT
WARP_CHAT_HOST_PORT=$WARP_CHAT_HOST_PORT
WARP_JAEGER_HOST_PORT=$WARP_JAEGER_HOST_PORT
EOF

cat > "$WORKTREE_OVERRIDE" <<EOF
# Generated by .devcontainer/initializeCommand.sh — do not edit or commit.
services:
  warp:
    ports: !override
      - "$WARP_GATEWAY_HOST_PORT:5000"
      - "$WARP_DEVELOPER_HOST_PORT:5002"
      - "$WARP_ADMIN_HOST_PORT:5003"
      - "$WARP_LATINUM_HOST_PORT:5004"
      - "$WARP_CHAT_HOST_PORT:8888"
  jaeger:
    ports: !override
      - "$WARP_JAEGER_HOST_PORT:16686"
  otel-collector:
    ports: !reset []
  redis:
    ports: !reset []
  memoryalpha-rag-api:
    ports: !reset []
  ollama:
    ports: !reset []
  stripe-mock:
    ports: !reset []
EOF

# A git worktree's .git file contains an absolute pointer into the main
# checkout's gitdir. Mount that gitdir at the same path inside the container.
if [ -f .git ]; then
    GITDIR="$(sed 's/^gitdir: //' .git)"
    if MAIN_GITDIR="$(cd "$(dirname "$GITDIR")/.." 2>/dev/null && pwd)" && [ -n "$MAIN_GITDIR" ]; then
        cat >> "$WORKTREE_OVERRIDE" <<EOF
    volumes:
      - ${MAIN_GITDIR}:${MAIN_GITDIR}:cached
EOF
        echo "Worktree detected; mounting main gitdir $MAIN_GITDIR into the devcontainer"
    else
        echo "Warning: could not resolve main gitdir from .git"
    fi
fi

echo "devcontainer host ports written to $PORTS_ENV"
cat "$PORTS_ENV"
